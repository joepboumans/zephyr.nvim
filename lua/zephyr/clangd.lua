-- clangd for the active Build configuration: a generated `.clangd` in the App
-- pointing at its compile_commands.json, and a clangd command whose
-- --query-driver lets clangd ask the Active toolchain's GCC for its headers.
local build_config = require("zephyr.build_config")
local events = require("zephyr.events")

local fs = require("zephyr.fs")

local M = {}

-- First line of every `.clangd` we write; a file without it is never touched.
M.MARKER = "# Generated by zephyr.nvim"

---GCC flags in Zephyr compile commands that clang rejects or warns about.
---Globs are allowed; newer clang may accept some of them.
M.default_remove = {
	"-fno-reorder-functions",
	"-mfp16-format=*",
	"-fno-printf-return-value",
	"-ftrack-macro-expansion=*",
	"-fno-tree-loop-distribute-patterns",
	"-fno-freestanding",
	"-fstrict-volatile-bitfields",
	"-fcallgraph-info*",
	"-mno-thumb-interwork",
	"-misa-spec=*",
	"-mlongcalls",
	"-mtext-section-literals",
	"-fno-defer-pop",
	"--param=*",
	"-specs=*",
	"--specs=*",
}

---Flags appended to every compile command, to quiet what is left of GCC-only flags.
M.default_add = { "-Wno-unknown-warning-option", "-Wno-unused-command-line-argument" }

---@class zephyr.ClangdConfig
---@field remove? string[] flags to drop from compile commands (replaces the default list)
---@field add? string[] flags to append to compile commands
---@field auto_write? boolean rewrite our `.clangd` when the Build configuration changes or a build succeeds

---@return zephyr.ClangdConfig
local function config()
	local c = require("zephyr").config.clangd or {}
	return {
		remove = c.remove or M.default_remove,
		add = c.add or M.default_add,
		auto_write = c.auto_write ~= false,
	}
end

---Path of the App's `.clangd`.
---@param app zephyr.App
function M.path(app)
	return app.dir .. "/.clangd"
end

---Who owns the App's `.clangd`.
---@param app zephyr.App
---@return "missing"|"generated"|"hand-written"
function M.status(app)
	local text = fs.read(M.path(app))
	if not text then
		return "missing"
	end
	return vim.startswith(text, M.MARKER) and "generated" or "hand-written"
end

-- A YAML double-quoted scalar. Not vim.json.encode: on Neovim 0.10 it writes `/` as `\/`.
local function quote(s)
	return '"'
		.. s:gsub('[%c"\\]', function(c)
			return ({ ['"'] = '\\"', ["\\"] = "\\\\", ["\n"] = "\\n", ["\t"] = "\\t" })[c]
				or ("\\x%02x"):format(c:byte())
		end)
		.. '"'
end

---The `.clangd` text for `cfg` of `app`. The database path is relative to the
---App when the build directory is inside it.
---@param app zephyr.App
---@param cfg zephyr.BuildConfig
---@param opts? { remove?: string[], add?: string[] } defaults to the setup options
---@return string
function M.content(app, cfg, opts)
	local c = config()
	opts = opts or {}
	local remove, add = opts.remove or c.remove, opts.add or c.add
	local db = cfg.image_dir
	if vim.startswith(db, app.dir .. "/") then
		db = db:sub(#app.dir + 2)
	end
	local lines = {
		("%s for build configuration %s%s. Delete this line to keep your own edits."):format(
			M.MARKER,
			cfg.name,
			cfg.board and (" (" .. cfg.board .. ")") or ""
		),
		"CompileFlags:",
		"  CompilationDatabase: " .. quote(db),
	}
	for _, section in ipairs({ { "Remove", remove }, { "Add", add } }) do
		if #section[2] > 0 then
			table.insert(lines, "  " .. section[1] .. ":")
			for _, flag in ipairs(section[2]) do
				table.insert(lines, "    - " .. quote(flag))
			end
		end
	end
	return table.concat(lines, "\n") .. "\n"
end

---@class zephyr.ClangdResult
---@field status "written"|"unchanged"|"hand-written"|"no-build-config"
---@field path string the `.clangd` file
---@field build_dir string|nil the active Build configuration
---@field database string|nil directory clangd reads compile_commands.json from
---@field has_database boolean false until the Build configuration has been built

---Write `<app>/.clangd` for the active Build configuration. A `.clangd` that
---we did not generate is left alone and reported as "hand-written".
---Fires ZephyrClangdWritten (`ev.data`: app, path, build_dir) when it writes.
---@param app zephyr.App
---@param opts? { remove?: string[], add?: string[] }
---@return boolean ok, zephyr.ClangdResult
function M.write(app, opts)
	local path = M.path(app)
	local cfg = build_config.active(app)
	if not cfg then
		return false, { status = "no-build-config", path = path, has_database = false }
	end
	local result = {
		path = path,
		build_dir = cfg.dir,
		database = cfg.image_dir,
		has_database = vim.uv.fs_stat(cfg.image_dir .. "/compile_commands.json") ~= nil,
	}
	local current = fs.read(path)
	if current and not vim.startswith(current, M.MARKER) then
		result.status = "hand-written"
		return false, result
	end
	local text = M.content(app, cfg, opts)
	if current == text then
		result.status = "unchanged"
		return true, result
	end
	local fd, err = io.open(path, "w")
	if not fd then
		error(("zephyr: cannot write %s: %s"):format(path, err))
	end
	fd:write(text)
	fd:close()
	result.status = "written"
	events.emit("ClangdWritten", { app = app.dir, path = path, build_dir = cfg.dir })
	return true, result
end

---Rewrite the `.clangd` of the App at `app_dir`, only if it is one we generated
---and auto_write is on. Used on ZephyrBuildConfigActivated and ZephyrBuildFinished.
---@param app_dir string
---@return boolean written
function M.refresh(app_dir)
	if not config().auto_write or not app_dir then
		return false
	end
	local app = require("zephyr.app").from_dir(app_dir)
	if M.status(app) ~= "generated" then
		return false
	end
	local pok, ok, res = pcall(M.write, app)
	return pok and ok and res.status == "written"
end

---The --query-driver glob(s) for `toolchain`'s GCC, comma separated.
---The Zephyr SDK keeps its GCCs in `<sdk>/<target>/bin` (0.16) or `<sdk>/gnu/<target>/bin` (0.17+).
---@param toolchain zephyr.Toolchain
---@return string
function M.query_driver(toolchain)
	local path = toolchain.path:gsub("/$", "")
	if toolchain.provider == "zephyr-sdk" then
		return path .. "/*/bin/*-gcc," .. path .. "/gnu/*/bin/*-gcc"
	end
	return path .. "/**/bin/*-gcc"
end

---The clangd command line for files of `workspace`, with --query-driver for
---the Active toolchain of `app`'s active Build configuration (by default the
---Workspace's Active app), else the Workspace's default Toolchain.
---@param workspace? zephyr.Workspace
---@param app? zephyr.App
---@return string[]
function M.cmd(workspace, app)
	local cmd = { "clangd" }
	local target = app or workspace
	local tc = target and require("zephyr.toolchain").active(target)
	if tc and tc.path then
		table.insert(cmd, "--query-driver=" .. M.query_driver(tc))
	end
	return cmd
end

---Start clangd with M.cmd() on C/C++ buffers inside a Workspace, rooted at
---their App (or the Workspace). Only runs when called; returns the autocmd id.
---@param opts? { filetypes?: string[], cmd?: fun(workspace: zephyr.Workspace, app: zephyr.App|nil): string[] }
---@return integer
function M.setup_lsp(opts)
	opts = opts or {}
	local group = vim.api.nvim_create_augroup("zephyr_clangd_lsp", { clear = true })
	return vim.api.nvim_create_autocmd("FileType", {
		group = group,
		pattern = opts.filetypes or { "c", "cpp" },
		callback = function(ev)
			local file = vim.api.nvim_buf_get_name(ev.buf)
			if file == "" or vim.bo[ev.buf].buftype ~= "" then
				return
			end
			local ws = require("zephyr.workspace").find(file)
			if not ws then
				return
			end
			local app = require("zephyr.app").find(file)
			vim.lsp.start({
				name = "clangd",
				cmd = (opts.cmd or M.cmd)(ws, app),
				root_dir = app and app.dir or ws.topdir,
			}, { bufnr = ev.buf })
		end,
	})
end

return M
