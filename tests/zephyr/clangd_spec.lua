local h = dofile("tests/helpers.lua")
local app_mod = require("zephyr.app")
local build_config = require("zephyr.build_config")
local clangd = require("zephyr.clangd")
local events = require("zephyr.events")
local registry = require("zephyr.registry")
local zephyr = require("zephyr")

local function read(path)
	return table.concat(vim.fn.readfile(path), "\n")
end

describe("clangd", function()
	local root, app, restore_state, saved_config

	before_each(function()
		restore_state = h.temp_state()
		saved_config = vim.deepcopy(zephyr.config)
		root = h.copy_fixture("builds/app")
		app = app_mod.from_dir(root)
	end)

	after_each(function()
		restore_state()
		zephyr.config = saved_config
	end)

	it("writes a marked .clangd pointing at the active image's compile_commands.json", function()
		zephyr.setup({ clangd = { remove = { "-fno-reorder-functions", "-mfp16-format=*" }, add = {} } })
		build_config.activate(app, build_config.read(root .. "/build_nrf5340dk_nrf5340_cpuapp"))
		local ok, res = clangd.write(app)
		assert.is_true(ok)
		assert.are.equal("written", res.status)
		assert.are.equal(root .. "/build_nrf5340dk_nrf5340_cpuapp/app", res.database)
		assert.is_false(res.has_database)
		assert.are.equal(
			table.concat({
				"# Generated by zephyr.nvim for build configuration build_nrf5340dk_nrf5340_cpuapp (nrf5340dk/nrf5340/cpuapp). Delete this line to keep your own edits.",
				"CompileFlags:",
				'  CompilationDatabase: "build_nrf5340dk_nrf5340_cpuapp/app"',
				"  Remove:",
				'    - "-fno-reorder-functions"',
				'    - "-mfp16-format=*"',
			}, "\n"),
			read(root .. "/.clangd")
		)
		assert.are.equal("generated", clangd.status(app))
	end)

	it("uses the default remove and add lists", function()
		clangd.write(app)
		local text = read(root .. "/.clangd")
		assert.truthy(text:find('CompilationDatabase: "build"', 1, true))
		for _, flag in ipairs(clangd.default_remove) do
			assert.truthy(text:find('    - "' .. flag .. '"', 1, true), flag)
		end
		assert.truthy(text:find('  Add:\n    - "-Wno-unknown-warning-option"', 1, true))
	end)

	it("keeps an absolute path for a build dir outside the App", function()
		local cfg = vim.tbl_extend("force", build_config.read(root .. "/build"), { image_dir = "/elsewhere/build" })
		assert.truthy(clangd.content(app, cfg):find('CompilationDatabase: "/elsewhere/build"', 1, true))
	end)

	it("notices an existing compile_commands.json", function()
		vim.fn.writefile({ "[]" }, root .. "/build/compile_commands.json")
		local _, res = clangd.write(app)
		assert.is_true(res.has_database)
	end)

	it("never overwrites a hand-written .clangd", function()
		vim.fn.writefile({ "CompileFlags:", "  Add: [-DMINE]" }, root .. "/.clangd")
		local ok, res = clangd.write(app)
		assert.is_false(ok)
		assert.are.equal("hand-written", res.status)
		assert.are.equal(root .. "/build", res.database)
		assert.are.equal("CompileFlags:\n  Add: [-DMINE]", read(root .. "/.clangd"))
	end)

	it("reports a missing build configuration", function()
		local empty = app_mod.from_dir(h.copy_fixture("workspace/app"))
		local ok, res = clangd.write(empty)
		assert.is_false(ok)
		assert.are.equal("no-build-config", res.status)
		assert.is_nil(vim.uv.fs_stat(empty.dir .. "/.clangd"))
	end)

	it("reports an unchanged file and fires ZephyrClangdWritten only on writes", function()
		local seen = 0
		local id = vim.api.nvim_create_autocmd("User", {
			pattern = "ZephyrClangdWritten",
			callback = function()
				seen = seen + 1
			end,
		})
		clangd.write(app)
		local _, res = clangd.write(app)
		vim.api.nvim_del_autocmd(id)
		assert.are.equal("unchanged", res.status)
		assert.are.equal(1, seen)
	end)

	describe("auto write", function()
		it("rewrites our .clangd when another build configuration is activated", function()
			clangd.write(app)
			build_config.activate(app, build_config.read(root .. "/build_nrf5340dk_nrf5340_cpuapp"))
			assert.truthy(read(root .. "/.clangd"):find('"build_nrf5340dk_nrf5340_cpuapp/app"', 1, true))
		end)

		it("rewrites our .clangd after a successful build only", function()
			clangd.write(app)
			-- Change the active configuration behind the plugin's back.
			local state = require("zephyr.state")
			state.set(root, { build_configs = { [root] = { dir = root .. "/out/nrf52dk_nrf52832" } } })
			events.emit("BuildFinished", { app = root, build_dir = root .. "/out/nrf52dk_nrf52832", ok = false })
			assert.truthy(read(root .. "/.clangd"):find('"build"', 1, true))
			events.emit("BuildFinished", { app = root, build_dir = root .. "/out/nrf52dk_nrf52832", ok = true })
			assert.truthy(read(root .. "/.clangd"):find('"out/nrf52dk_nrf52832"', 1, true))
		end)

		it("leaves a hand-written or missing .clangd alone", function()
			build_config.activate(app, build_config.read(root .. "/build_nrf5340dk_nrf5340_cpuapp"))
			assert.is_nil(vim.uv.fs_stat(root .. "/.clangd"))
			vim.fn.writefile({ "CompileFlags: {}" }, root .. "/.clangd")
			build_config.activate(app, build_config.read(root .. "/build"))
			assert.are.equal("CompileFlags: {}", read(root .. "/.clangd"))
		end)

		it("can be turned off", function()
			zephyr.setup({ clangd = { auto_write = false } })
			clangd.write(app)
			build_config.activate(app, build_config.read(root .. "/build_nrf5340dk_nrf5340_cpuapp"))
			assert.truthy(read(root .. "/.clangd"):find('CompilationDatabase: "build"', 1, true))
		end)
	end)

	describe("cmd", function()
		local ws = { topdir = "/ws" }
		local function provide(name, path)
			registry.register("toolchain_provider", {
				name = name,
				find = function()
					return { { provider = name, id = name, name = name, version = "1", path = path } }
				end,
				env = function()
					return {}
				end,
			})
		end

		before_each(function()
			registry._reset()
		end)

		after_each(function()
			registry._reset()
			registry.register("toolchain_provider", require("zephyr.sdk").provider)
		end)

		it("globs both Zephyr SDK GCC layouts", function()
			provide("zephyr-sdk", "/opt/zephyr-sdk-0.17.0")
			assert.are.same({
				"clangd",
				"--query-driver=/opt/zephyr-sdk-0.17.0/*/bin/*-gcc,/opt/zephyr-sdk-0.17.0/gnu/*/bin/*-gcc",
			}, clangd.cmd(ws))
		end)

		it("globs any bin dir of other toolchains", function()
			provide("ncs", "/opt/ncs/toolchains/b8b84efebd/")
			assert.are.same(
				{ "clangd", "--query-driver=/opt/ncs/toolchains/b8b84efebd/**/bin/*-gcc" },
				clangd.cmd(ws)
			)
		end)

		it("is plain clangd without a toolchain", function()
			assert.are.same({ "clangd" }, clangd.cmd(ws))
			assert.are.same({ "clangd" }, clangd.cmd(nil))
		end)
	end)

	it("starts clangd on C buffers inside a Workspace once set up", function()
		local wsroot = h.copy_fixture("workspace")
		local started = {}
		local saved = vim.lsp.start
		vim.lsp.start = function(cfg, opts)
			table.insert(started, { cfg = cfg, opts = opts, file = vim.api.nvim_buf_get_name(opts.bufnr) })
		end
		local id = clangd.setup_lsp({
			cmd = function(ws)
				return { "clangd", "--ws=" .. ws.topdir }
			end,
		})
		vim.cmd("edit " .. wsroot .. "/app/src/main.c")
		vim.cmd("setfiletype c")
		local outside = vim.fn.tempname() .. ".c"
		vim.cmd("edit " .. outside)
		vim.cmd("setfiletype c")
		vim.lsp.start = saved
		vim.api.nvim_del_autocmd(id)
		vim.cmd("silent! %bwipeout!")
		-- FileType may fire more than once per buffer; vim.lsp.start reuses the client then.
		assert.is_true(#started >= 1)
		for _, s in ipairs(started) do
			assert.are.equal(wsroot .. "/app/src/main.c", s.file)
		end
		assert.are.same({ "clangd", "--ws=" .. wsroot }, started[1].cfg.cmd)
		assert.are.equal("clangd", started[1].cfg.name)
	end)
end)

describe(":Zephyr clangd", function()
	local root, restore_state, notes, saved_notify

	before_each(function()
		restore_state = h.temp_state()
		root = h.copy_fixture("builds/app")
		notes = {}
		saved_notify = vim.notify
		vim.notify = function(msg, level)
			table.insert(notes, { msg = msg, level = level })
		end
	end)

	after_each(function()
		vim.notify = saved_notify
		restore_state()
		vim.cmd("silent! %bwipeout!")
	end)

	it("writes .clangd and says where it points", function()
		vim.cmd("edit " .. root .. "/src/main.c")
		vim.cmd("Zephyr clangd")
		assert.is_not_nil(vim.uv.fs_stat(root .. "/.clangd"))
		assert.truthy(notes[1].msg:find("wrote", 1, true))
		assert.truthy(notes[1].msg:find(root .. "/build", 1, true))
		assert.truthy(notes[1].msg:find("no compile_commands.json yet", 1, true))
	end)

	it("explains why it left a hand-written .clangd alone", function()
		vim.fn.writefile({ "CompileFlags: {}" }, root .. "/.clangd")
		vim.cmd("edit " .. root .. "/src/main.c")
		vim.cmd("Zephyr clangd")
		assert.are.equal(vim.log.levels.WARN, notes[1].level)
		assert.truthy(notes[1].msg:find("not written by zephyr.nvim", 1, true))
		assert.are.equal("CompileFlags: {}", read(root .. "/.clangd"))
	end)
end)
